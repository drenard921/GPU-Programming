static bool parseArgs(int argc, char** argv, AppConfig& config) {
    for (int i = 1; i < argc; ++i) {
        if (argv[i] == nullptr) {
            continue;
        }

        std::string arg = argv[i];

        if (arg == "--help" || arg == "-h") {
            printUsage(argv[0]);
            return false;
        }

        if (arg == "--mode") {
            if (i + 1 >= argc || !parseModeArg(argv[++i], config.mode)) {
#ifdef USE_CUDA
                std::cerr << "Invalid value for --mode. Use cpu, cuda, or replay.\n";
#else
                std::cerr << "Invalid value for --mode. Use cpu or replay.\n";
#endif
                return false;
            }
            continue;
        }

        if (arg == "--step") {
            if (i + 1 >= argc || !parseStepArg(argv[++i], config.stepSelection)) {
                std::cerr
                    << "Invalid value for --step. Use protocol, load, concentrate, wash, or harvest.\n";
                return false;
            }
            continue;
        }

        if (arg == "--particles") {
            if (i + 1 >= argc ||
                !parseIntArg(argv[++i], config.totalParticles)) {
                std::cerr << "Invalid value for --particles. Use a positive integer.\n";
                return false;
            }
            continue;
        }

        if (arg == "--duration") {
            if (i + 1 >= argc ||
                !parseFloatArg(argv[++i], config.durationSeconds)) {
                std::cerr << "Invalid value for --duration. Use a positive number.\n";
                return false;
            }
            continue;
        }

        if (arg == "--steps") {
            if (i + 1 >= argc ||
                !parseIntArg(argv[++i], config.benchmarkSteps)) {
                std::cerr << "Invalid value for --steps. Use a positive integer.\n";
                return false;
            }
            continue;
        }

        if (arg == "--headless") {
            config.headless = true;
            continue;
        }

        if (arg == "--replay") {
            if (i + 1 >= argc || argv[i + 1] == nullptr) {
                std::cerr << "Missing path after --replay.\n";
                return false;
            }

            config.replayPath = argv[++i];
            continue;
        }

        std::cerr << "Unknown argument: " << arg << "\n";
        printUsage(argv[0]);
        return false;
    }

    if (config.mode == RunMode::Replay && config.replayPath.empty()) {
        std::cerr << "Replay mode requires --replay PATH.\n";
        return false;
    }

    if (config.headless && config.mode == RunMode::Replay) {
        std::cerr << "Headless mode supports cpu or cuda, not replay.\n";
        return false;
    }

    if (config.headless && config.benchmarkSteps <= 0) {
        if (config.durationSeconds > 0.0f) {
            config.benchmarkSteps =
                std::max(1, static_cast<int>(config.durationSeconds / 0.016f));
        } else {
            config.benchmarkSteps = 10000;
        }
    }

    if (config.mode == RunMode::Replay &&
        config.stepSelection != StepSelection::Protocol) {
        std::cerr
            << "Note: --step is ignored in replay mode because replay frames are precomputed.\n";
    }

    return true;
}

static bool validateReplayHeader(const ReplayHeader& header) {
    const char expectedMagic[8] = {'R', 'O', 'T', 'E', 'A', 'F', 'R', 'M'};

    if (std::memcmp(header.magic, expectedMagic, 8) != 0) {
        std::cerr << "Invalid replay file magic.\n";
        return false;
    }

    if (header.version != 1) {
        std::cerr << "Unsupported replay file version: "
                  << header.version << "\n";
        return false;
    }

    if (header.particleCount == 0 || header.frameCount == 0) {
        std::cerr << "Replay file has invalid particle/frame count.\n";
        return false;
    }

    if (!std::isfinite(header.dt) || header.dt <= 0.0f) {
        std::cerr << "Replay file has invalid dt.\n";
        return false;
    }

    return true;
}

static bool loadReplayFile(const std::string& path, ReplayData& replay) {
    std::ifstream in(path, std::ios::binary);

    if (!in) {
        std::cerr << "Failed to open replay file: " << path << "\n";
        return false;
    }

    ReplayHeader header{};
    in.read(reinterpret_cast<char*>(&header), sizeof(header));

    if (!in || !validateReplayHeader(header)) {
        std::cerr << "Failed to read valid replay header.\n";
        return false;
    }

    const std::size_t particleCount =
        static_cast<std::size_t>(header.particleCount);
    const std::size_t frameCount =
        static_cast<std::size_t>(header.frameCount);

    if (particleCount > std::numeric_limits<std::size_t>::max() / frameCount) {
        std::cerr << "Replay particle/frame count overflow.\n";
        return false;
    }

    const std::size_t totalParticles = particleCount * frameCount;

    if (totalParticles >
        std::numeric_limits<std::size_t>::max() / sizeof(Particle)) {
        std::cerr << "Replay byte count overflow.\n";
        return false;
    }

    const std::size_t totalBytes = totalParticles * sizeof(Particle);
    const std::size_t maxReplayBytes =
        static_cast<std::size_t>(2ULL * 1024ULL * 1024ULL * 1024ULL);

    if (totalBytes > maxReplayBytes) {
        std::cerr
            << "Replay file too large to load safely: "
            << totalBytes
            << " bytes. Generate fewer frames while debugging.\n";
        return false;
    }

    replay.particleCount = static_cast<int>(header.particleCount);
    replay.frameCount = static_cast<int>(header.frameCount);
    replay.dt = header.dt;

    replay.frames.resize(totalParticles);

    in.read(
        reinterpret_cast<char*>(replay.frames.data()),
        static_cast<std::streamsize>(totalBytes)
    );

    if (!in) {
        std::cerr << "Replay file ended before all particle frames were read.\n";
        return false;
    }

    std::cout
        << "Loaded replay file: " << path << "\n"
        << "Replay particles: " << replay.particleCount << "\n"
        << "Replay frames: " << replay.frameCount << "\n"
        << "Replay dt: " << replay.dt << "\n";

    return true;
}

static GLFWwindow* createWindow(const AppConfig& config) {
    glfwSetErrorCallback(glfw_error_callback);

    if (!glfwInit()) {
        std::cerr << "Failed to initialize GLFW.\n";
        return nullptr;
    }

    std::string title;

    if (config.mode == RunMode::Cpu) {
        title = "Rotea CPU/OpenGL Particle Simulation";
    } else if (config.mode == RunMode::Cuda) {
        title = "Rotea CUDA/OpenGL Particle Simulation";
    } else {
        title = "Rotea CUDA Frame Replay Visualization";
    }

    GLFWwindow* window = glfwCreateWindow(
        1200,
        800,
        title.c_str(),
        nullptr,
        nullptr
    );

    if (!window) {
        std::cerr << "Failed to create GLFW window.\n";
        glfwTerminate();
        return nullptr;
    }

    glfwMakeContextCurrent(window);
    glfwSwapInterval(1);

    glEnable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    return window;
}

