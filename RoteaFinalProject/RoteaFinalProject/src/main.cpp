static constexpr int CHAMBER_NODE = -1;

// =============================================================================
// main.cpp — Application entry point and runtime controller
//
// Provides:
//   1. Command-line parsing for CPU, CUDA, replay, visual, and headless modes
//   2. Protocol setup for load, concentrate, wash, harvest, and full protocol runs
//   3. Visual OpenGL simulation loop
//   4. Headless benchmark loop for update-only timing
//   5. Benchmark summary reporting for CPU/CUDA/replay comparisons
//
// Notes:
//   - Visual mode measures the full synchronous application loop:
//       system update + particle update + render/swap/poll.
//   - Headless mode skips OpenGL and isolates update-loop performance.
//   - Replay mode visualizes particle frames generated by the CUDA frame generator.
// =============================================================================

enum class RunMode {
    Cpu,
    Cuda,
    Replay
};

enum class StepSelection {
    Protocol,
    Load,
    Concentrate,
    Wash,
    Harvest
};

struct AppConfig {
    RunMode mode = RunMode::Cpu;
    int totalParticles = 5000;
    float durationSeconds = -1.0f;
    int benchmarkSteps = 0;
    bool headless = false;
    std::string replayPath;
    StepSelection stepSelection = StepSelection::Protocol;
};

struct GeometryConfig {
    float chamberHeight = 2.5f;

    // y = -height/2 is the narrow inlet/tip.
    // y = +height/2 is the wider upper chamber.
    float outerBase = 0.28f;
    float outerTip  = 1.15f;

    float innerBase = 0.12f;
    float innerTip  = 0.55f;
};

struct BenchmarkStats {
    int frames = 0;
    double totalRuntimeMs = 0.0;
    double fullFrameMs = 0.0;
    double particleUpdateMs = 0.0;
    double systemUpdateMs = 0.0;
    double renderMs = 0.0;
};

struct ReplayHeader {
    char magic[8];
    std::uint32_t version;
    std::uint32_t particleCount;
    std::uint32_t frameCount;
    float dt;
};

struct ReplayData {
    int particleCount = 0;
    int frameCount = 0;
    float dt = 0.016f;
    std::vector<Particle> frames;
};

static void glfw_error_callback(int error, const char* description) {
    std::cerr << "GLFW Error [" << error << "]: "
              << (description ? description : "unknown") << std::endl;
}

static double nowSeconds() {
    using clock = std::chrono::high_resolution_clock;
    static const auto start = clock::now();
    const auto current = clock::now();
    return std::chrono::duration<double>(current - start).count();
}

static double secondsToMs(double seconds) {
    return seconds * 1000.0;
}

