static std::vector<Particle> initLiveParticles(
    const AppConfig& config,
    const GeometryConfig& geometry
) {
    const int total = std::max(1, config.totalParticles);

    int cellParticles = std::max(1, total / 10);

    if (total == 1) {
        cellParticles = 1;
    }

    const int fluidParticles = total - cellParticles;

    std::vector<Particle> particles = initParticles(
        fluidParticles,
        cellParticles,
        geometry.chamberHeight,
        geometry.outerBase,
        geometry.outerTip,
        geometry.innerBase,
        geometry.innerTip
    );

    std::cout
        << "Particles: " << particles.size()
        << " total (" << fluidParticles << " fluid, "
        << cellParticles << " cells)\n";

    return particles;
}

static float computeChamberFlow(
    const std::vector<Line>& lines,
    const Step& step
) {
    float chamberFlow = 0.0f;

    for (const auto& line : lines) {
        if (!line.active) {
            continue;
        }

        if (line.sourceBag == CHAMBER_NODE ||
            line.targetBag == CHAMBER_NODE) {
            chamberFlow += step.flow_ml_min[static_cast<int>(line.id)];
        }
    }

    return chamberFlow;
}

// Advances one CPU simulation step: process-level system update followed by
// CPU particle update. Timing is accumulated separately for system and particle
// work so benchmarks can report where time is spent.
static void updateCpuFrame(
    std::vector<Particle>& particles,
    std::vector<Bag>& bags,
    std::vector<Line>& lines,
    Chamber& chamber,
    std::vector<Step>& protocol,
    int& currentStep,
    float& stepTimer,
    float dt,
    const GeometryConfig& geometry,
    BenchmarkStats& stats
) {
    Step& step = protocol[currentStep];

    const double systemStart = nowSeconds();

    updateSystem(bags, lines, chamber, step, dt);
    const float chamberFlow = computeChamberFlow(lines, step);

    const double systemEnd = nowSeconds();
    stats.systemUpdateMs += secondsToMs(systemEnd - systemStart);

    const double particleStart = nowSeconds();

    updateParticles(
        particles,
        dt,
        step.g_force,
        chamberFlow,
        geometry.chamberHeight,
        geometry.outerBase,
        geometry.outerTip,
        geometry.innerBase,
        geometry.innerTip
    );

    const double particleEnd = nowSeconds();
    stats.particleUpdateMs += secondsToMs(particleEnd - particleStart);

    stepTimer += dt;

    if (stepTimer >= step.duration_s) {
        std::cout
            << "Phase complete: " << step.name
            << " | retained=" << chamber.retained_cells
            << " | suspended=" << chamber.suspended_cells
            << " | omega=" << chamber.omega
            << std::endl;

        stepTimer = 0.0f;
        currentStep = (currentStep + 1) % static_cast<int>(protocol.size());
    }
}

