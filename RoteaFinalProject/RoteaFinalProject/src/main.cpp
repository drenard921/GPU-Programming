// Advances one CUDA simulation step. Process-level state is still updated on
// the CPU, while particle positions are updated by the CUDA backend.
// Timing includes live CUDA transfer, kernel execution, synchronization, and
// copy-back because the renderer consumes CPU-side particle data.
static bool updateCudaFrame(
    std::vector<Particle>& particles,
    std::vector<Bag>& bags,
    std::vector<Line>& lines,
    Chamber& chamber,
    std::vector<Step>& protocol,
    int& currentStep,
    float& stepTimer,
    float dt,
    const GeometryConfig& geometry,
    BenchmarkStats& stats
) {
    Step& step = protocol[currentStep];

    const double systemStart = nowSeconds();

    updateSystem(bags, lines, chamber, step, dt);
    const float chamberFlow = computeChamberFlow(lines, step);

    const double systemEnd = nowSeconds();
    stats.systemUpdateMs += secondsToMs(systemEnd - systemStart);

    const double particleStart = nowSeconds();

    const bool ok = updateParticlesCUDA(
        particles.data(),
        static_cast<int>(particles.size()),
        dt,
        step.g_force,
        chamberFlow,
        geometry.chamberHeight,
        geometry.outerBase,
        geometry.outerTip,
        geometry.innerBase,
        geometry.innerTip,
        phaseToInt(step.phase)
    );

    const double particleEnd = nowSeconds();
    stats.particleUpdateMs += secondsToMs(particleEnd - particleStart);

    if (!ok) {
        std::cerr << "CUDA particle update failed.\n";
        return false;
    }

    stepTimer += dt;

    if (stepTimer >= step.duration_s) {
        std::cout
            << "Phase complete: " << step.name
            << " | retained=" << chamber.retained_cells
            << " | suspended=" << chamber.suspended_cells
            << " | omega=" << chamber.omega
            << std::endl;

        stepTimer = 0.0f;
        currentStep = (currentStep + 1) % static_cast<int>(protocol.size());
    }

    return true;
}
