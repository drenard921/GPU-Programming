static void updateReplayFrame(
    const ReplayData& replay,
    std::vector<Particle>& particles,
    int& replayFrame
) {
    if (replay.frameCount <= 0 || replay.particleCount <= 0 ||
        replay.frames.empty()) {
        return;
    }

    const int frameIndex = replayFrame % replay.frameCount;

    const std::size_t offset =
        static_cast<std::size_t>(frameIndex) *
        static_cast<std::size_t>(replay.particleCount);

    const std::size_t count =
        static_cast<std::size_t>(replay.particleCount);

    if (offset + count > replay.frames.size()) {
        std::cerr << "Replay frame offset out of range.\n";
        return;
    }

    particles.assign(
        replay.frames.begin() + static_cast<std::ptrdiff_t>(offset),
        replay.frames.begin() + static_cast<std::ptrdiff_t>(offset + count)
    );

    ++replayFrame;
}

static bool sanitizeParticlesForRender(
    std::vector<Particle>& particles,
    const GeometryConfig& geometry,
    const char* source
) {
    bool repairedAny = false;
    int repairedCount = 0;

    const float halfH = geometry.chamberHeight * 0.5f;
    const float maxR = std::max(geometry.outerBase, geometry.outerTip) * 1.05f;

    for (std::size_t i = 0; i < particles.size(); ++i) {
        Particle& p = particles[i];
        bool bad = false;

        if (!std::isfinite(p.x) || !std::isfinite(p.y) || !std::isfinite(p.z) ||
            !std::isfinite(p.vx) || !std::isfinite(p.vy) || !std::isfinite(p.vz) ||
            !std::isfinite(p.diameter) || !std::isfinite(p.density)) {
            bad = true;
        }

        if (p.type != 0 && p.type != 1) {
            bad = true;
        }

        if (p.diameter <= 0.0f || p.diameter > 1.0f) {
            bad = true;
        }

        if (p.density <= 0.0f || p.density > 5.0f) {
            bad = true;
        }

        if (std::fabs(p.x) > maxR * 4.0f ||
            std::fabs(p.z) > maxR * 4.0f ||
            std::fabs(p.y) > geometry.chamberHeight * 4.0f) {
            bad = true;
        }

        if (bad) {
            if (repairedCount < 5) {
                std::cerr
                    << "[PARTICLE SANITIZER] " << source
                    << " repaired particle " << i
                    << " pos=(" << p.x << ", " << p.y << ", " << p.z << ")"
                    << " vel=(" << p.vx << ", " << p.vy << ", " << p.vz << ")"
                    << " type=" << p.type
                    << " diameter=" << p.diameter
                    << " density=" << p.density
                    << "\n";
            }

            p.x = 0.35f;
            p.y = -0.45f * geometry.chamberHeight;
            p.z = 0.0f;
            p.vx = 0.0f;
            p.vy = 0.0f;
            p.vz = 0.0f;
            p.type = 0;
            p.diameter = 0.06f;
            p.density = 1.0f;

            repairedAny = true;
            ++repairedCount;
        } else {
            p.y = std::max(-halfH, std::min(halfH, p.y));
            p.x = std::max(-maxR, std::min(maxR, p.x));
            p.z = std::max(-maxR, std::min(maxR, p.z));
            p.diameter = std::max(0.01f, std::min(0.25f, p.diameter));
        }
    }

    if (repairedCount > 0) {
        std::cerr << "[PARTICLE SANITIZER] repaired " << repairedCount
                  << " invalid particles from " << source
                  << " before rendering.\n";
    }

    return repairedAny;
}

// Renders one OpenGL frame: projection setup, chamber geometry, particles,
// buffer swap, and event polling. This work is intentionally excluded from
// headless benchmark mode.
static void renderFrame(
    GLFWwindow* window,
    const GeometryConfig& geometry,
    const std::vector<Particle>& particles
) {
    int fbWidth = 0;
    int fbHeight = 0;
    glfwGetFramebufferSize(window, &fbWidth, &fbHeight);

    glViewport(0, 0, fbWidth, fbHeight);
    glClearColor(0.05f, 0.05f, 0.08f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);

    setupProjection(fbWidth, fbHeight);

    glLoadIdentity();
    glTranslatef(0.0f, 0.0f, -5.0f);
    glRotatef(20.0f, 1.0f, 0.0f, 0.0f);
    glRotatef(
        static_cast<float>(glfwGetTime()) * 6.0f,
        0.0f,
        1.0f,
        0.0f
    );

    drawNestedConeChamber(
        geometry.outerBase,
        geometry.outerTip,
        geometry.innerBase,
        geometry.innerTip,
        geometry.chamberHeight
    );

    drawParticles(particles);

    glfwSwapBuffers(window);
    glfwPollEvents();
}

// Prints a common benchmark summary for visual, headless, and replay runs.
// The same summary format is parsed by the Python benchmark scripts.
static void printBenchmarkSummary(
    const BenchmarkStats& stats,
    std::size_t particleCount,
    RunMode mode,
    StepSelection stepSelection
) {
    const double totalSeconds = stats.totalRuntimeMs / 1000.0;
    const double safeSeconds = std::max(totalSeconds, 1e-9);
    const int safeFrames = std::max(stats.frames, 1);

    const double fps = static_cast<double>(stats.frames) / safeSeconds;
    const double avgFrameMs = stats.fullFrameMs / safeFrames;
    const double avgSystemMs = stats.systemUpdateMs / safeFrames;
    const double avgParticleMs = stats.particleUpdateMs / safeFrames;
    const double avgRenderMs = stats.renderMs / safeFrames;

    std::cout << std::fixed << std::setprecision(4);

    std::cout << "\n========== Benchmark Summary ==========\n";
    std::cout << "Mode: " << modeName(mode) << "\n";
    std::cout << "Step: " << stepName(stepSelection) << "\n";
    std::cout << "Particles: " << particleCount << "\n";
    std::cout << "Frames: " << stats.frames << "\n";
    std::cout << "Overall runtime: " << totalSeconds << " s\n";
    std::cout << "Average FPS: " << fps << "\n";
    std::cout << "Average full frame runtime: " << avgFrameMs << " ms/frame\n";
    std::cout << "Average system update runtime: " << avgSystemMs << " ms/frame\n";

    if (mode == RunMode::Cpu) {
        std::cout << "Average CPU particle update runtime: "
                  << avgParticleMs
                  << " ms/frame\n";

        std::cout << "Total CPU particle update runtime: "
                  << stats.particleUpdateMs / 1000.0
                  << " s\n";
    } else if (mode == RunMode::Cuda) {
        std::cout << "Average CUDA particle update runtime: "
                  << avgParticleMs
                  << " ms/frame\n";

        std::cout << "Total CUDA particle update runtime: "
                  << stats.particleUpdateMs / 1000.0
                  << " s\n";
    } else {
        std::cout << "Replay particle-frame copy runtime: "
                  << avgParticleMs
                  << " ms/frame\n";
        std::cout << "Replay note: particles were precomputed by the CUDA frame generator.\n";
    }

    std::cout << "Average render/swap/poll runtime: "
              << avgRenderMs
              << " ms/frame\n";

    std::cout << "=======================================\n";
}

// Runs the simulation update loop without creating an OpenGL window.
// This isolates CPU/CUDA update cost from rendering and display-loop overhead,
// making it the cleanest benchmark for particle-update performance.
static int runHeadlessBenchmark(const AppConfig& config) {
    GeometryConfig geometry;
    std::vector<Particle> particles = initLiveParticles(config, geometry);

    std::vector<Bag> bags;
    Chamber chamber{};
    std::vector<Line> lines;
    std::vector<Step> protocol;

    initCpuProtocol(
        bags,
        chamber,
        lines,
        protocol,
        config.stepSelection
    );

#ifdef USE_CUDA
    if (config.mode == RunMode::Cuda) {
        std::cerr << "[CUDA ENGINE] using persistent CUDA particle buffer\n";

        if (!initCudaParticleBuffer(static_cast<int>(particles.size()))) {
            std::cerr << "Failed to initialize CUDA particle buffer.\n";
            return 1;
        }
    }
#endif

    std::cout << "Mode: " << modeName(config.mode) << "\n";
    std::cout << "Step: " << stepName(config.stepSelection) << "\n";
    std::cout << "Headless: true\n";
    std::cout << "Update steps: " << config.benchmarkSteps << "\n";

    const float dt = 0.016f;
    int currentStep = 0;
    float stepTimer = 0.0f;

    BenchmarkStats stats;
    const double benchmarkStart = nowSeconds();

    for (int i = 0; i < config.benchmarkSteps; ++i) {
        const double frameStart = nowSeconds();

        if (config.mode == RunMode::Cpu) {
            updateCpuFrame(
                particles,
                bags,
                lines,
                chamber,
                protocol,
                currentStep,
                stepTimer,
                dt,
                geometry,
                stats
            );
        } else if (config.mode == RunMode::Cuda) {
#ifdef USE_CUDA
            if (!updateCudaFrame(
                    particles,
                    bags,
                    lines,
                    chamber,
                    protocol,
                    currentStep,
                    stepTimer,
                    dt,
                    geometry,
                    stats)) {
                shutdownCudaParticleBuffer();
                return 1;
            }
#else
            std::cerr
                << "CUDA mode requested, but this binary was built without CUDA support.\n";
            return 1;
#endif
        }

        const double frameEnd = nowSeconds();
        stats.fullFrameMs += secondsToMs(frameEnd - frameStart);
        stats.frames++;
    }

    const double benchmarkEnd = nowSeconds();
    stats.totalRuntimeMs = secondsToMs(benchmarkEnd - benchmarkStart);

    std::cout << "\n========== Headless Benchmark ==========\n";
    std::cout << "Mode: " << modeName(config.mode) << "\n";
    std::cout << "Step: " << stepName(config.stepSelection) << "\n";
    std::cout << "Particles: " << particles.size() << "\n";
    std::cout << "Update steps: " << config.benchmarkSteps << "\n";
    std::cout << "Simulated seconds: " << config.benchmarkSteps * dt << "\n";
    std::cout << "=======================================\n";

    printBenchmarkSummary(
        stats,
        particles.size(),
        config.mode,
        config.stepSelection
    );

#ifdef USE_CUDA
    if (config.mode == RunMode::Cuda) {
        shutdownCudaParticleBuffer();
    }
#endif

    return 0;
}

// Runs the interactive OpenGL application.
// This path measures end-to-end visual performance, including simulation update,
// CUDA transfer/synchronization when applicable, rendering, buffer swap, and
// event polling.
static int runApp(const AppConfig& config) {
    GeometryConfig geometry;
    ReplayData replay;
    std::vector<Particle> particles;

    if (config.mode == RunMode::Replay) {
        if (!loadReplayFile(config.replayPath, replay)) {
            return 1;
        }

        particles.resize(static_cast<std::size_t>(replay.particleCount));
    } else {
        particles = initLiveParticles(config, geometry);

#ifdef USE_CUDA
        if (config.mode == RunMode::Cuda) {
            std::cerr << "[CUDA ENGINE] using persistent CUDA particle buffer\n";
        }
#endif
    }

    GLFWwindow* window = createWindow(config);

    if (!window) {
        return 1;
    }

    std::cout << "Mode: " << modeName(config.mode) << "\n";
    std::cout << "Step: " << stepName(config.stepSelection) << "\n";

    if (config.durationSeconds > 0.0f) {
        std::cout << "Duration: " << config.durationSeconds << " seconds\n";
    } else {
        std::cout << "Duration: indefinite. Press ESC to exit.\n";
    }

    std::vector<Bag> bags;
    Chamber chamber{};
    std::vector<Line> lines;
    std::vector<Step> protocol;

    int currentStep = 0;
    float stepTimer = 0.0f;
    int replayFrame = 0;

    if (config.mode == RunMode::Cpu || config.mode == RunMode::Cuda) {
        initCpuProtocol(
            bags,
            chamber,
            lines,
            protocol,
            config.stepSelection
        );
    }

#ifdef USE_CUDA
    if (config.mode == RunMode::Cuda) {
        if (!initCudaParticleBuffer(static_cast<int>(particles.size()))) {
            std::cerr << "Failed to initialize CUDA particle buffer.\n";
            glfwDestroyWindow(window);
            glfwTerminate();
            return 1;
        }
    }
#endif

    const float cpuDt = 0.016f;
    float elapsedTime = 0.0f;

    BenchmarkStats stats;
    const double appStartTime = nowSeconds();

    while (!glfwWindowShouldClose(window)) {
        const double frameStart = nowSeconds();

        if (config.mode == RunMode::Cpu) {
            updateCpuFrame(
                particles,
                bags,
                lines,
                chamber,
                protocol,
                currentStep,
                stepTimer,
                cpuDt,
                geometry,
                stats
            );

            elapsedTime += cpuDt;
        } else if (config.mode == RunMode::Cuda) {
#ifdef USE_CUDA
            if (!updateCudaFrame(
                    particles,
                    bags,
                    lines,
                    chamber,
                    protocol,
                    currentStep,
                    stepTimer,
                    cpuDt,
                    geometry,
                    stats)) {
                glfwSetWindowShouldClose(window, GLFW_TRUE);
                break;
            }

            elapsedTime += cpuDt;
#else
            std::cerr
                << "CUDA mode requested, but this binary was built without CUDA support.\n";
            glfwSetWindowShouldClose(window, GLFW_TRUE);
#endif
        } else {
            const double replayStart = nowSeconds();

            updateReplayFrame(replay, particles, replayFrame);

            const double replayEnd = nowSeconds();
            stats.particleUpdateMs += secondsToMs(replayEnd - replayStart);

            elapsedTime += replay.dt;
        }

        if (config.mode == RunMode::Cpu) {
            sanitizeParticlesForRender(particles, geometry, "cpu");
        } else if (config.mode == RunMode::Cuda) {
            sanitizeParticlesForRender(particles, geometry, "cuda");
        } else {
            sanitizeParticlesForRender(particles, geometry, "replay");
        }

        if (config.durationSeconds > 0.0f &&
            elapsedTime >= config.durationSeconds) {
            std::cout
                << "Requested duration reached: "
                << config.durationSeconds
                << " seconds. Exiting.\n";

            glfwSetWindowShouldClose(window, GLFW_TRUE);
        }

        const double renderStart = nowSeconds();

        renderFrame(window, geometry, particles);

        const double renderEnd = nowSeconds();
        stats.renderMs += secondsToMs(renderEnd - renderStart);

        if (glfwGetKey(window, GLFW_KEY_ESCAPE) == GLFW_PRESS) {
            glfwSetWindowShouldClose(window, GLFW_TRUE);
        }

        const double frameEnd = nowSeconds();
        stats.fullFrameMs += secondsToMs(frameEnd - frameStart);
        stats.frames++;
    }

    const double appEndTime = nowSeconds();
    stats.totalRuntimeMs = secondsToMs(appEndTime - appStartTime);

    printBenchmarkSummary(
        stats,
        particles.size(),
        config.mode,
        config.stepSelection
    );

#ifdef USE_CUDA
    if (config.mode == RunMode::Cuda) {
        shutdownCudaParticleBuffer();
    }
#endif

    glfwDestroyWindow(window);
    glfwTerminate();

    return 0;
}

int main(int argc, char** argv) {
    AppConfig config;

    if (!parseArgs(argc, argv, config)) {
        return 1;
    }

    if (config.headless) {
        return runHeadlessBenchmark(config);
    }

    return runApp(config);
}