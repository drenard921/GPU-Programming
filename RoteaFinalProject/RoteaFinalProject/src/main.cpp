static bool parseIntArg(const char* value, int& out) {
    if (value == nullptr) {
        return false;
    }

    char* end = nullptr;
    long parsed = std::strtol(value, &end, 10);

    if (end == value || *end != '\0' || parsed <= 0 ||
        parsed > std::numeric_limits<int>::max()) {
        return false;
    }

    out = static_cast<int>(parsed);
    return true;
}

static bool parseFloatArg(const char* value, float& out) {
    if (value == nullptr) {
        return false;
    }

    char* end = nullptr;
    float parsed = std::strtof(value, &end);

    if (end == value || *end != '\0' || parsed <= 0.0f ||
        !std::isfinite(parsed)) {
        return false;
    }

    out = parsed;
    return true;
}

static bool parseModeArg(const std::string& value, RunMode& out) {
    if (value == "cpu") {
        out = RunMode::Cpu;
        return true;
    }

#ifdef USE_CUDA
    if (value == "cuda") {
        out = RunMode::Cuda;
        return true;
    }
#else
    if (value == "cuda") {
        std::cerr
            << "This binary was built without CUDA support. "
            << "Use --mode cpu/replay or rebuild with USE_CUDA.\n";
        return false;
    }
#endif

    if (value == "replay") {
        out = RunMode::Replay;
        return true;
    }

    return false;
}

